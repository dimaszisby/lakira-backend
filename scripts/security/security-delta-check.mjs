#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";

const ROOT = process.cwd();
const DEFAULT_OUTPUT = path.join(
  ROOT,
  "tmp/security/security-delta-report.json",
);
const DEFAULT_AUDIT_RAW = path.join(
  ROOT,
  "tmp/security/npm-audit-production.json",
);

const parseArgs = () => {
  const args = process.argv.slice(2);
  const out = { output: DEFAULT_OUTPUT, auditRaw: DEFAULT_AUDIT_RAW };

  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--output") {
      out.output = path.resolve(ROOT, args[i + 1]);
      i += 1;
    } else if (arg === "--audit-raw") {
      out.auditRaw = path.resolve(ROOT, args[i + 1]);
      i += 1;
    }
  }

  return out;
};

const severityOrder = ["critical", "high", "medium", "low", "info"];

const normalizeSeverity = (value) => {
  const v = String(value ?? "low").toLowerCase();
  if (v === "moderate") return "medium";
  return severityOrder.includes(v) ? v : "low";
};

const addDays = (date, days) => {
  const d = new Date(date);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString();
};

const addHours = (date, hours) => {
  const d = new Date(date);
  d.setUTCHours(d.getUTCHours() + hours);
  return d.toISOString();
};

const computeSlaDue = (severity, baseDate) => {
  switch (severity) {
    case "critical":
      return addHours(baseDate, 24);
    case "high":
      return addDays(baseDate, 7);
    case "medium":
      return addDays(baseDate, 30);
    default:
      return addDays(baseDate, 90);
  }
};

const parseJsonSafely = (raw) => {
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
};

const runNpmAudit = async (auditRawPath, nowIso) => {
  const result = spawnSync("npm", ["audit", "--production", "--json"], {
    cwd: ROOT,
    encoding: "utf8",
    shell: false,
    maxBuffer: 1024 * 1024 * 16,
  });

  const rawOut = (result.stdout || "").trim();
  const rawErr = (result.stderr || "").trim();
  const parsed = parseJsonSafely(rawOut) ?? parseJsonSafely(rawErr) ?? {};

  await fs.mkdir(path.dirname(auditRawPath), { recursive: true });
  await fs.writeFile(auditRawPath, JSON.stringify(parsed, null, 2), "utf8");

  const vulnerabilities = parsed.vulnerabilities ?? {};
  const findings = [];

  for (const [pkg, vuln] of Object.entries(vulnerabilities)) {
    const severity = normalizeSeverity(vuln?.severity);
    const cveOrGhsa = Array.isArray(vuln?.via)
      ? vuln.via
          .filter((v) => typeof v === "object" && v !== null)
          .map((v) => {
            if (Array.isArray(v.cwe) && v.cwe.length > 0)
              return v.cwe.join(", ");
            return v.url || v.source || v.name;
          })
          .filter(Boolean)
          .join(", ")
      : "";

    findings.push({
      id: `AUTO-NPM-${pkg}`,
      title: `Vulnerable dependency detected: ${pkg}`,
      domain: "dependency-supply-chain",
      severity,
      cvss: "n/a",
      likelihood:
        severity === "critical" || severity === "high" ? "high" : "medium",
      impact: severity === "critical" ? "critical" : severity,
      businessRisk:
        "Known vulnerable dependency may expose runtime or tooling attack surface.",
      status: "open",
      owner: "backend-security",
      source: "npm_audit_production",
      owaspAsvsRef: "V14.2",
      owaspTop10Ref: "A06",
      nistSsdfRef: "RV.1",
      cweRef: cveOrGhsa || "n/a",
      affectedAssets: "Application runtime and dependency chain",
      entryPoints: "Dependency tree",
      evidenceRefs: [path.relative(ROOT, auditRawPath)],
      reproSteps: "Run npm audit --production --json",
      targetFixVersion:
        severity === "critical" || severity === "high"
          ? "next-patch"
          : "backlog",
      slaDueDate: computeSlaDue(severity, nowIso),
      verifiedDate: "",
      notes: "Generated by security delta automation.",
    });
  }

  return {
    command: "npm audit --production --json",
    exitCode: result.status ?? 1,
    hadParseableOutput: Object.keys(parsed).length > 0,
    vulnerabilitiesCount: findings.length,
    findings,
  };
};

const readText = async (relativePath) => {
  const fullPath = path.join(ROOT, relativePath);
  const text = await fs.readFile(fullPath, "utf8");
  return { fullPath, text };
};

const hasRegex = (text, regex) => regex.test(text);

const buildStaticFinding = ({
  id,
  title,
  severity,
  description,
  evidenceRefs,
  owaspAsvsRef,
  owaspTop10Ref,
  nistSsdfRef,
  cweRef = "n/a",
  nowIso,
}) => ({
  id,
  title,
  domain: "configuration-hardening",
  severity,
  cvss: "n/a",
  likelihood:
    severity === "high" || severity === "critical" ? "high" : "medium",
  impact: severity,
  businessRisk: description,
  status: "open",
  owner: "backend-security",
  source: "static_guardrail_scan",
  owaspAsvsRef,
  owaspTop10Ref,
  nistSsdfRef,
  cweRef,
  affectedAssets: "Backend runtime and API surface",
  entryPoints: "Configuration and middleware",
  evidenceRefs,
  reproSteps: "Run node scripts/security/security-delta-check.mjs",
  targetFixVersion:
    severity === "high" || severity === "critical" ? "next-patch" : "backlog",
  slaDueDate: computeSlaDue(severity, nowIso),
  verifiedDate: "",
  notes: "Generated by static guardrail checks.",
});

const runStaticChecks = async (nowIso) => {
  const findings = [];
  const rules = [];

  const server = await readText("src/server.ts");
  const zodEnv = await readText("src/config/zodEnv.ts");
  const dbConfig = await readText("src/config/db.ts");
  const sequelizeConfig = await readText("src/config/config.cjs");

  const ruleTls = {
    id: "CFG-TLS-001",
    passed:
      !hasRegex(dbConfig.text, /rejectUnauthorized\s*:\s*false/) &&
      !hasRegex(sequelizeConfig.text, /rejectUnauthorized\s*:\s*false/),
  };
  rules.push(ruleTls);
  if (!ruleTls.passed) {
    findings.push(
      buildStaticFinding({
        id: "AUTO-CFG-TLS-001",
        title: "Database TLS verification disabled in configuration",
        severity: "high",
        description:
          "TLS certificate validation should not be hard-coded to false.",
        evidenceRefs: ["src/config/db.ts", "src/config/config.cjs"],
        owaspAsvsRef: "V9",
        owaspTop10Ref: "A02",
        nistSsdfRef: "PW.4",
        cweRef: "CWE-295",
        nowIso,
      }),
    );
  }

  // `.prefault` is zod 4's spelling of a default that is parsed like a sent value, which
  // a default followed by a transform needs (zod-4-migration D-04); either counts.
  const ruleSwaggerDefault = {
    id: "CFG-SWAGGER-001",
    passed: hasRegex(
      zodEnv.text,
      /SWAGGER_REQUIRE_AUTH[\s\S]*?\.(?:default|prefault)\("true"\)/,
    ),
  };
  rules.push(ruleSwaggerDefault);
  if (!ruleSwaggerDefault.passed) {
    findings.push(
      buildStaticFinding({
        id: "AUTO-CFG-SWAGGER-001",
        title: "Swagger auth guard default is not hardened",
        severity: "high",
        description: "Swagger docs should require authentication by default.",
        evidenceRefs: ["src/config/zodEnv.ts", "src/server.ts"],
        owaspAsvsRef: "V14",
        owaspTop10Ref: "A05",
        nistSsdfRef: "PW.6",
        nowIso,
      }),
    );
  }

  const ruleRateLimitDefault = {
    id: "CFG-RATE-LIMIT-001",
    passed: hasRegex(
      zodEnv.text,
      /DISABLE_RATE_LIMITING[\s\S]*?\.(?:default|prefault)\("false"\)/,
    ),
  };
  rules.push(ruleRateLimitDefault);
  if (!ruleRateLimitDefault.passed) {
    findings.push(
      buildStaticFinding({
        id: "AUTO-CFG-RATE-LIMIT-001",
        title: "Rate limiting can be disabled by insecure default",
        severity: "high",
        description:
          "DISABLE_RATE_LIMITING should default to false to prevent accidental abuse exposure.",
        evidenceRefs: [
          "src/config/zodEnv.ts",
          "src/shared/middleware/rate-limiter.ts",
        ],
        owaspAsvsRef: "V7",
        owaspTop10Ref: "A04",
        nistSsdfRef: "PW.6",
        nowIso,
      }),
    );
  }

  const hasPatchRoutes =
    hasRegex(server.text, /router\.patch\(/) ||
    hasRegex(
      await fs.readFile(
        path.join(
          ROOT,
          "src/features/public/metric-settings/infrastructure/http/router.ts",
        ),
        "utf8",
      ),
      /router\.patch\(/,
    );
  const corsMethodsMatch = server.text.match(/methods\s*:\s*\[(.*?)\]/s);
  const corsMethodsBlock = corsMethodsMatch ? corsMethodsMatch[1] : "";
  const corsHasPatch = /"PATCH"|'PATCH'/.test(corsMethodsBlock);
  const ruleCorsPatch = {
    id: "CFG-CORS-001",
    passed: !hasPatchRoutes || corsHasPatch,
  };
  rules.push(ruleCorsPatch);
  if (!ruleCorsPatch.passed) {
    findings.push(
      buildStaticFinding({
        id: "AUTO-CFG-CORS-001",
        title: "CORS allow-methods omits PATCH while PATCH routes exist",
        severity: "medium",
        description:
          "Browser clients may bypass intended route behavior and create security/control inconsistencies.",
        evidenceRefs: [
          "src/server.ts",
          "src/features/public/metric-settings/infrastructure/http/router.ts",
        ],
        owaspAsvsRef: "V14",
        owaspTop10Ref: "A05",
        nistSsdfRef: "RV.1",
        nowIso,
      }),
    );
  }

  const authSchema = await readText(
    "src/features/shared/auth/infrastructure/http/schema.zod.ts",
  );
  const updateUseCase = await readText(
    "src/features/shared/auth/application/use-cases/UpdateProfile.ts",
  );

  const rulePrivilegedRoleInput = {
    id: "AUTHZ-ROLE-001",
    passed:
      !/role\s*:\s*zRoleEnum\.optional\(\)/.test(authSchema.text) &&
      !/if \(input\.role/.test(updateUseCase.text),
  };
  rules.push(rulePrivilegedRoleInput);
  if (!rulePrivilegedRoleInput.passed) {
    findings.push(
      buildStaticFinding({
        id: "AUTO-AUTHZ-ROLE-001",
        title: "User profile update flow still accepts privileged role input",
        severity: "high",
        description:
          "Role should be excluded from user-controlled profile update DTOs to prevent future escalation regressions.",
        evidenceRefs: [
          "src/features/shared/auth/infrastructure/http/schema.zod.ts",
          "src/features/shared/auth/application/use-cases/UpdateProfile.ts",
        ],
        owaspAsvsRef: "V4",
        owaspTop10Ref: "A01",
        nistSsdfRef: "PW.5",
        cweRef: "CWE-266",
        nowIso,
      }),
    );
  }

  return {
    rules,
    findings,
  };
};

const countBySeverity = (findings) =>
  findings.reduce(
    (acc, finding) => {
      const severity = normalizeSeverity(finding.severity);
      acc[severity] = (acc[severity] ?? 0) + 1;
      return acc;
    },
    { critical: 0, high: 0, medium: 0, low: 0, info: 0 },
  );

const main = async () => {
  const { output, auditRaw } = parseArgs();
  const nowIso = new Date().toISOString();

  await fs.mkdir(path.dirname(output), { recursive: true });

  const npmAudit = await runNpmAudit(auditRaw, nowIso);
  const staticChecks = await runStaticChecks(nowIso);

  const findings = [...npmAudit.findings, ...staticChecks.findings];
  const severityCounts = countBySeverity(findings);

  const report = {
    schemaVersion: "1.0.0",
    generatedAtUtc: nowIso,
    baseline: {
      asvs: "v4 L2",
      top10: "OWASP Top 10 2021",
      ssdf: "NIST SP 800-218",
    },
    checks: {
      npmAudit,
      staticGuardrails: {
        executed: true,
        rules: staticChecks.rules,
        findingsCount: staticChecks.findings.length,
      },
    },
    findings,
    summary: {
      totalFindings: findings.length,
      severityCounts,
      unresolvedHighCritical:
        (severityCounts.critical ?? 0) + (severityCounts.high ?? 0),
    },
    artifacts: {
      npmAuditRaw: path.relative(ROOT, auditRaw),
    },
  };

  await fs.writeFile(output, JSON.stringify(report, null, 2), "utf8");

  console.log("[security:delta] Security delta check complete");
  console.log(`[security:delta] Output: ${path.relative(ROOT, output)}`);
  console.log(
    `[security:delta] Findings total=${report.summary.totalFindings} critical=${severityCounts.critical} high=${severityCounts.high} medium=${severityCounts.medium} low=${severityCounts.low}`,
  );
};

main().catch((error) => {
  console.error(`[security:delta] ${error.message}`);
  process.exit(1);
});
